// 00-version.js — 全体のバージョン名（Builder側・飛行側の両方が読む）
//
// 番号プレフィックス方式なので、いちばん小さい番号を付けてどのページでも最初に読む。
// ここが**唯一の出どころ**。他の場所に版番号を書き写さないこと。
//
// ---- 名前の形 ------------------------------------------------------------
//
//   APP_VERSION = '00.005.000.000'
//                  ^^ ^^^ ^^^ ^^^
//                  │   │   │   └─ 変更（3桁）… 1つの変更ごとに +1
//                  │   │   └───── 節（3桁）… まとまった機能追加・変更ごとに +1
//                  │   └───────── 柱（3桁）… 新しい仕組みが1本立つごとに +1
//                  └───────────── 大版（2桁）… 保存データやファイル構成の互換が切れたら +1
//
// 上の桁が上がったら、それより下の桁は 000 に戻す。
//
// ---- どこで上げるか ------------------------------------------------------
//
// ・**変更**（いちばん下の3桁）… コミット1つぶん。バグ1つを直した、小さな機能を
//   足した、という単位。README と CHANGELOG に何をしたかを書いて、ここを +1 する。
// ・**節**（下から2つめ）… その方向の作業がひととおり終わったところ。
//   たとえば「着陸まわりを直しきった」「音を入れ終えた」。
//   **ここを上げるときにアーカイブを控える**（下の説明を参照）。
// ・**柱**（下から3つめ）… 前に無かった仕組みが1本増えたとき。
//   これまでで言えば「世界」「飛行」「自動操縦」「エンジンと排気」がそれぞれ1本。
// ・**大版**（いちばん上）… 保存した機体データや設定が読めなくなる作り替えをしたとき。
//   いまは 00（まだ一度も切っていない）。
//
// ---- アーカイブとバージョン切り替え --------------------------------------
//
// 節が上がるたびに、そのときのコミットのハッシュを CHANGELOG.md の見出しに控える。
// それがアーカイブで、`git checkout <ハッシュ>` でその版がそのまま動く。
//
// ファイルを `archive/` に丸ごとコピーする形も考えたが、この構成では
// 1版で約1.5MB増える（.git 全体が11MBしかない）。Gitはもともと全部の版を
// 持っているので、コピーは同じものを二重に持つだけで、リポジトリを重くする以外の
// 効果がない。**ハッシュを控えるだけなら0バイトで同じことができる**。
//
// タグ（git tag）のほうが名前で呼べて読みやすいが、この作業環境からはタグを
// push できない（開発ブランチへの push だけが許されていて、タグは403で弾かれる）。
// タグが欲しければ GitHub の Releases でハッシュを選んで付ければ同じものになる。
//
// ブラウザの中から版を切り替えるには、版の数だけアプリを並べて置く必要があり、
// 上の理由で割に合わないので入れていない。
//
// ---- 番号を付ける前の歴史 ------------------------------------------------
//
// バージョン名を付けはじめたのは 00.005.000.000 から。それまでに立った柱を
// さかのぼって数えると4本あったので、5本目の頭から始めている。
// （00.001＝世界、00.002＝飛行、00.003＝自動操縦、00.004＝エンジンと排気、
//   00.005＝見た目の作り込み（煙・灯り・雲底・夜）、00.006＝音、
//   00.007＝モデルのボーンを動かす、00.008＝モデル形状からの当たり判定、
//   00.009＝パフォーマンス設定（画質プリセット）、00.010＝森の見え方、
//   00.011＝川の河口（入り江・三角州）、00.012＝山脈の稜線、00.013＝道路と街路。
//   それぞれの中身は CHANGELOG.md を参照）
//
// **柱が上がるときは、前の柱の開いていた節をそこで閉じる**（節が上がるのと同じ
// 扱いで、そのときアーカイブのハッシュを控える）。柱が上がると節は000に戻るので、
// そうしないと前の柱の最後のぶんがアーカイブされないまま流れてしまう。
const APP_VERSION = '00.013.004.002';

// 画面に出すときの名前（「v」は付けない。Gitのタグだけ v を付ける）
function appVersionLabel() { return APP_VERSION; }
